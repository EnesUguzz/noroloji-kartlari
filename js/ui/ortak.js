// Ekranların ortak küçük yardımcıları.
export function esc(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

// Cevap metni: her satır bir madde; tek satırsa paragraf.
export function cevapHtml(a) {
  const satirlar = String(a).split('\n').map((l) => l.trim()).filter(Boolean);
  if (satirlar.length === 1) return '<p>' + esc(satirlar[0]) + '</p>';
  return '<ul>' + satirlar.map((l) => '<li>' + esc(l) + '</li>').join('') + '</ul>';
}

